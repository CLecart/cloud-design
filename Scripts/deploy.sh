#!/usr/bin/env bash
# Deploy the application on the EKS cluster created by terraform/platform.
#
#   1. add the cluster to ~/.kube/config (context "cloud-design")
#   2. check that the six images exist in ECR with the wanted tag
#   3. generate the missing Secrets (Scripts/generate-secrets.sh) and apply them
#   4. apply Manifests/ through a kustomize overlay that points every container
#      to <registry>/cloud-design/<image>:<tag>
#   5. wait until every workload is ready
#
# Prerequisites: terraform/platform applied, images pushed (Scripts/push-images.sh).
#
# Usage: Scripts/deploy.sh
#
# Environment:
#   AWS_REGION  Region of the cluster and the registry (default: aws configure get region, else eu-west-3)
#   IMAGE_TAG   tag to deploy (default: short Git commit, the tag push-images.sh uses)
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT="cloud-design"
NAMESPACE="cloud-design"
IMAGES=(api-gateway inventory-app inventory-database billing-app billing-database rabbitmq-server)
OVERLAY_DIR="$ROOT_DIR/.deploy"

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  sed -n '2,/^set -euo/p' "$0" | sed '$d' | cut -c3-
  exit 0
fi

for tool in aws kubectl terraform git; do
  command -v "$tool" >/dev/null 2>&1 || { echo "error: $tool is not installed" >&2; exit 1; }
done

region="${AWS_REGION:-$(aws configure get region || true)}"
region="${region:-eu-west-3}"
account="$(aws sts get-caller-identity --query Account --output text)"
registry="$account.dkr.ecr.$region.amazonaws.com"
tag="${IMAGE_TAG:-$(git -C "$ROOT_DIR" rev-parse --short HEAD)}"
cluster="$(terraform -chdir="$ROOT_DIR/terraform/platform" output -raw cluster_name)"

echo "== cluster $cluster ($region)"
aws eks update-kubeconfig --region "$region" --name "$cluster" --alias "$PROJECT" >/dev/null
kubectl config use-context "$PROJECT" >/dev/null

echo "== images $registry/$PROJECT/*:$tag"
for image in "${IMAGES[@]}"; do
  aws ecr describe-images --region "$region" --repository-name "$PROJECT/$image" \
    --image-ids imageTag="$tag" --query 'imageDetails[0].imageTags' --output text >/dev/null 2>&1 ||
    { echo "error: $PROJECT/$image:$tag is not in ECR, run Scripts/push-images.sh first" >&2; exit 1; }
done

echo "== secrets"
"$ROOT_DIR/Scripts/generate-secrets.sh"
kubectl apply -f "$ROOT_DIR/Manifests/namespace.yaml"
kubectl apply -n "$NAMESPACE" -f "$ROOT_DIR/Manifests/secrets/"

echo "== manifests"
# The overlay is generated at every run (ignored by Git): only the image names change.
mkdir -p "$OVERLAY_DIR"
{
  echo "# Generated by Scripts/deploy.sh, do not edit."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  echo "  - ../Manifests"
  echo "images:"
  for image in "${IMAGES[@]}"; do
    echo "  - name: $image"
    echo "    newName: $registry/$PROJECT/$image"
    echo "    newTag: \"$tag\""
  done
} >"$OVERLAY_DIR/kustomization.yaml"
kubectl apply -k "$OVERLAY_DIR"

echo "== waiting for the workloads"
for workload in statefulset/inventory-db statefulset/billing-db statefulset/rabbitmq \
  deployment/inventory-app statefulset/billing-app deployment/api-gateway; do
  kubectl -n "$NAMESPACE" rollout status "$workload" --timeout=10m
done

echo
kubectl -n "$NAMESPACE" get pods -o wide
echo
echo "deployed tag $tag; internal load balancer: http://$(terraform -chdir="$ROOT_DIR/terraform/platform" output -raw alb_dns_name)"
